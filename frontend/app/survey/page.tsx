"use client";
import React, { useState, useEffect } from "react";
import { fetcher } from "@/lib/api";
import { FileText, CheckCircle2, ArrowRight, UserCheck, HelpCircle } from "lucide-react";

type SurveyItem = {
  item_id: string;
  cve_id: string;
  condition: string;
  narrative_text: string;
};

export default function SurveyPage() {
  const [items, setItems] = useState<SurveyItem[]>([]);
  const [currentIndex, setCurrentIndex] = useState(0);
  const [raterId, setRaterId] = useState("");
  const [started, setStarted] = useState(false);

  const [rating, setRating] = useState<number | null>(null);
  const [wouldAct, setWouldAct] = useState<boolean | null>(null);
  const [submitting, setSubmitting] = useState(false);
  const [done, setDone] = useState(false);

  useEffect(() => {
    fetcher("/survey/items?count=5").then((d) => setItems(d.items || []));
  }, []);

  const handleStart = (e: React.FormEvent) => {
    e.preventDefault();
    if (raterId.trim() && items.length > 0) setStarted(true);
  };

  const handleSubmit = async () => {
    if (!rating || wouldAct === null) return;
    setSubmitting(true);

    const currentItem = items[currentIndex];
    try {
      await fetcher("/survey/responses", {
        method: "POST",
        body: JSON.stringify({
          item_id: currentItem.item_id,
          cve_id: currentItem.cve_id,
          condition: currentItem.condition,
          rater_id: raterId,
          clarity_rating: rating,
          would_act: wouldAct,
        }),
      });

      setRating(null);
      setWouldAct(null);

      if (currentIndex < items.length - 1) {
        setCurrentIndex((prev) => prev + 1);
      } else {
        setDone(true);
      }
    } catch (e) {
      alert("Failed to record survey evaluation.");
    }
    setSubmitting(false);
  };

  if (items.length === 0) {
    return (
      <div className="p-16 text-center text-gray-500 dark:text-[#94A3B8] bg-white dark:bg-[#111827] rounded-2xl border border-gray-200 dark:border-[#273449] max-w-xl mx-auto mt-12 transition-colors">
        <div className="w-8 h-8 border-2 border-[#ED7D24] border-t-transparent rounded-full animate-spin mx-auto mb-3" />
        <p className="font-semibold text-gray-800 dark:text-slate-200">Loading blinded survey items...</p>
        <p className="text-xs text-gray-400 dark:text-slate-500 mt-1">Make sure narratives have been generated in the corpus.</p>
      </div>
    );
  }

  if (!started) {
    return (
      <div className="max-w-xl mx-auto mt-12 bg-white dark:bg-[#111827] p-8 rounded-2xl shadow-2xs border border-gray-200/90 dark:border-[#273449] space-y-6 transition-colors">
        <div className="flex items-center gap-3">
          <div className="p-2.5 rounded-xl bg-purple-50 dark:bg-purple-950/60 text-purple-700 dark:text-purple-300">
            <FileText size={22} />
          </div>
          <div>
            <span className="text-[11px] font-bold uppercase tracking-wider text-purple-700 dark:text-purple-300 block">
              Human Evaluation Protocol
            </span>
            <h1 className="text-2xl font-black text-gray-950 dark:text-[#F8FAFC] tracking-tight">
              KEVIDENCE Blinded Evaluation Survey
            </h1>
          </div>
        </div>

        <p className="text-sm text-gray-600 dark:text-[#94A3B8] leading-relaxed">
          You will evaluate plain-English vulnerability risk narratives generated by the KEVIDENCE engine.
          Please review each randomized statement and rate its clarity and decision-making sufficiency.
        </p>

        <form onSubmit={handleStart} className="space-y-4 pt-2">
          <div>
            <label className="block text-xs font-bold uppercase tracking-wider text-gray-700 dark:text-slate-300 mb-1.5">
              Participant / Evaluator ID
            </label>
            <input
              type="text"
              required
              value={raterId}
              onChange={(e) => setRaterId(e.target.value)}
              className="w-full px-4 py-2.5 bg-gray-50 dark:bg-[#172033] border border-gray-200 dark:border-[#273449] text-gray-900 dark:text-[#F8FAFC] rounded-xl text-sm font-medium focus:bg-white dark:focus:bg-[#0B1120] focus:ring-2 focus:ring-[#ED7D24]/20 focus:border-[#ED7D24] transition-all"
              placeholder="e.g. rater-01"
            />
          </div>

          <button
            type="submit"
            className="w-full bg-gray-900 hover:bg-black dark:bg-[#ED7D24] dark:hover:bg-[#D96B16] text-white font-bold py-3 rounded-xl transition-colors shadow-2xs text-sm focus:outline-none focus-visible:ring-2 focus-visible:ring-[#ED7D24]"
          >
            Start Blinded Evaluation ({items.length} items)
          </button>
        </form>
      </div>
    );
  }

  if (done) {
    return (
      <div className="max-w-md mx-auto mt-16 bg-white dark:bg-[#111827] p-8 rounded-2xl shadow-2xs border border-gray-200 dark:border-[#273449] text-center space-y-4 transition-colors">
        <div className="w-16 h-16 rounded-full bg-emerald-100 dark:bg-emerald-950/80 text-emerald-600 dark:text-emerald-400 flex items-center justify-center mx-auto border dark:border-emerald-800">
          <CheckCircle2 size={32} />
        </div>
        <h1 className="text-2xl font-bold text-gray-900 dark:text-[#F8FAFC] tracking-tight">Thank You!</h1>
        <p className="text-sm text-gray-600 dark:text-[#94A3B8]">Your blinded survey ratings have been recorded into the evaluation database.</p>
      </div>
    );
  }

  const currentItem = items[currentIndex];

  return (
    <div className="max-w-2xl mx-auto mt-6 space-y-6 transition-colors">
      <div className="flex items-center justify-between text-xs text-gray-500 dark:text-[#94A3B8] font-medium px-2">
        <span>Evaluator: <strong className="text-gray-900 dark:text-[#F8FAFC]">{raterId}</strong></span>
        <span>Progress: <strong className="text-gray-900 dark:text-[#F8FAFC] font-mono">{currentIndex + 1} / {items.length}</strong></span>
      </div>

      <div className="bg-white dark:bg-[#111827] p-8 rounded-2xl shadow-2xs border border-gray-200/90 dark:border-[#273449] space-y-4">
        <span className="text-[11px] font-bold text-gray-400 dark:text-slate-500 uppercase tracking-wider block">
          Blinded Item &bull; Condition: {currentItem.condition}
        </span>
        <p className="text-lg text-gray-900 dark:text-[#F8FAFC] leading-relaxed font-serif">
          {currentItem.narrative_text}
        </p>
      </div>

      <div className="bg-white dark:bg-[#111827] p-6 rounded-2xl shadow-2xs border border-gray-200/90 dark:border-[#273449] space-y-8">
        <div>
          <h3 className="text-sm font-bold text-gray-900 dark:text-[#F8FAFC] mb-3">
            1. How clear and easy to understand is this narrative?
          </h3>
          <div className="flex justify-between items-center bg-gray-50 dark:bg-[#172033] p-2 rounded-xl border dark:border-[#273449]">
            <span className="text-xs text-gray-500 dark:text-[#94A3B8] px-2 font-medium">Very Confusing</span>
            {[1, 2, 3, 4, 5].map((val) => (
              <button
                key={val}
                type="button"
                onClick={() => setRating(val)}
                className={`w-11 h-11 rounded-xl font-bold text-sm transition-all focus:outline-none focus-visible:ring-2 focus-visible:ring-[#ED7D24] ${
                  rating === val
                    ? "bg-[#ED7D24] text-white ring-4 ring-orange-200 dark:ring-orange-500/40"
                    : "bg-white dark:bg-[#0B1120] text-gray-700 dark:text-slate-200 border border-gray-200 dark:border-[#273449] hover:border-gray-400 dark:hover:border-slate-500"
                }`}
              >
                {val}
              </button>
            ))}
            <span className="text-xs text-gray-500 dark:text-[#94A3B8] px-2 font-medium">Very Clear</span>
          </div>
        </div>

        <div>
          <h3 className="text-sm font-bold text-gray-900 dark:text-[#F8FAFC] mb-3">
            2. Do you feel you have enough evidence to make an operational decision?
          </h3>
          <div className="flex gap-4">
            <button
              type="button"
              onClick={() => setWouldAct(true)}
              className={`flex-1 py-3 rounded-xl font-semibold text-xs sm:text-sm border transition-all focus:outline-none focus-visible:ring-2 focus-visible:ring-[#ED7D24] ${
                wouldAct === true
                  ? "bg-emerald-50 dark:bg-emerald-950/60 border-emerald-500 text-emerald-800 dark:text-emerald-300 ring-2 ring-emerald-200 dark:ring-emerald-700/40"
                  : "bg-white dark:bg-[#172033] text-gray-700 dark:text-slate-300 border-gray-200 dark:border-[#273449] hover:border-gray-300 dark:hover:border-slate-600"
              }`}
            >
              Yes &bull; Sufficient Evidence
            </button>
            <button
              type="button"
              onClick={() => setWouldAct(false)}
              className={`flex-1 py-3 rounded-xl font-semibold text-xs sm:text-sm border transition-all focus:outline-none focus-visible:ring-2 focus-visible:ring-[#ED7D24] ${
                wouldAct === false
                  ? "bg-red-50 dark:bg-red-950/60 border-red-500 text-red-800 dark:text-red-300 ring-2 ring-red-200 dark:ring-red-700/40"
                  : "bg-white dark:bg-[#172033] text-gray-700 dark:text-slate-300 border-gray-200 dark:border-[#273449] hover:border-gray-300 dark:hover:border-slate-600"
              }`}
            >
              No &bull; Insufficient Context
            </button>
          </div>
        </div>

        <button
          type="button"
          onClick={handleSubmit}
          disabled={!rating || wouldAct === null || submitting}
          className="w-full bg-gray-900 hover:bg-black dark:bg-[#ED7D24] dark:hover:bg-[#D96B16] text-white font-bold py-3.5 rounded-xl transition-all disabled:opacity-40 disabled:cursor-not-allowed text-sm shadow-2xs focus:outline-none focus-visible:ring-2 focus-visible:ring-[#ED7D24]"
        >
          {submitting ? "Submitting Rating..." : "Next Item →"}
        </button>
      </div>
    </div>
  );
}
